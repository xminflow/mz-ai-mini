// 因此新增或改写条目时，先数字数。
//
// 左短右长是有意的版面表态：行规一句话说完，我们的做法需要展开讲。
// ours 不要跟着压缩到一行，那会把这层对比抹平。
//
// 左列在页面上标为「常见做法」而不是「别人」：官网上点名同行会掉价，
// 而「常见做法」既保住了分寸，立场又足够清楚。
//
// 第 03/04/05 条与合作流程第 07 步「维修保障」谈的是同一批承诺，这是有意的：
// 流程那一节讲「我们会做什么」，这一节讲「和别人比差在哪」，视角不同，措辞也已错开。
// 修改任一处时另一处要跟着核对，不要让两边出现互相矛盾的数字（如响应时长）。
//
// 本文件不含 JSX 与客户端逻辑。

